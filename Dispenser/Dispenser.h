#ifndef DISPENSER_H
#define DISPENSER_H

#include <Arduino.h>

// ============================================================
//  Dispenser - שליטה במנוע סרוו ללא Servo.h
//  מימוש PWM ידני על ESP32 דרך LEDC (LED Control peripheral)
//
//  איך מנוע סרוו סטנדרטי מבין לאיזו זווית להסתובב?
//  הוא מקבל אות מחזורי בתדר של 50Hz (כלומר 50 פולסים בשנייה. מחזור מלא לוקח 20ms).
//  אורך הפולס החשמלי קובע את הזווית:
//     - פולס באורך 1.0 ms יסובב את המנוע ל-0°  (מהווה 5% מתוך מחזור של 20ms)
//     - פולס באורך 1.5 ms יסובב את המנוע ל-90° (מהווה 7.5% מתוך מחזור של 20ms)
//     - פולס באורך 2.0 ms יסובב את המנוע ל-180°(מהווה 10% מתוך מחזור של 20ms)
// ============================================================

// הגדרות חומרה עבור מנוע הסרוו
// #define SERVO_PIN       13     // הפין הפיזי בלוח אליו מחובר חוט הנתונים של הסרוו
#define SERVO_CHANNEL   0      // ערוץ ה-LEDC הפנימי ב-ESP32 שנעשה בו שימוש (ישנם ערוצים 0-15)
#define SERVO_FREQ      50     // הגדרת התדר ל-50 הרץ (התדר הסטנדרטי הדרוש למנועי סרוו)

// רזולוציית האות: קובעת לכמה "מדרגות" המעבד מחלק את פולס החשמל.
// 16 ביט משמעותו טווח מספרים של בין 0 ל-65535. ככל שהרזולוציה גבוהה יותר, התנועה של המנוע חלקה ומדויקת יותר.
#define SERVO_RES_BITS  16     

// חישוב ערכי ה-Duty Cycle (עוצמת הפולס) המקבילים לזוויות הקיצון, מתוך הטווח של 16 ביט (65535):
// נוסחה: duty = (זמן הפולס במילישניות / 20 מילישניות) * 65535
#define SERVO_MIN_DUTY  3276   // החישוב: (1.0ms / 20ms) * 65535 = 3276.8 -> מתאים ל-0 מעלות
#define SERVO_MAX_DUTY  6553   // החישוב: (2.0ms / 20ms) * 65535 = 6553.5 -> מתאים ל-180 מעלות

// הגדרות הפעולה של קופסת התרופות
#define LOCKED_ANGLE    0      // המצב הרגיל: זווית 0 שומרת על תא התרופות נעול וסגור
#define OPEN_ANGLE      90     // מצב פתיחה: סיבוב המנוע ל-90 מעלות כדי לאפשר לכדור ליפול החוצה
#define DISPENSE_MS     800    // משך הזמן (0.8 שניות) שהתא יישאר פתוח לפני שהמנוע יסגור אותו חזרה

class Dispenser {
private:
    int servoPin;
    int targetAngle;           // משתנה פנימי השומר את הזווית אליה המנוע צריך להגיע כרגע

    // פונקציה פנימית המקבלת זווית רגילה במעלות (0 עד 180) 
    // ומחשבת איזה מספר דיגיטלי בטווח (3276-6553) צריך לשלוח לחומרה של ה-ESP32
    uint32_t angleToDuty(int angle);

public:
    // הבנאי 
    Dispenser(int serPin);
    //אתחול
    void begin();
    
    // פונקציה פנימית שמבצעת פיזית את שינוי האות החשמלי כדי להזיז את הסרוו לזווית המבוקשת
    void setAngle(int angle);

    // הפונקציה המרכזית: מקבלת את מספר התא ממנו צריך לשחרר תרופה
    // מסובבת את המנוע, מחכה 800 מילישניות שהכדור ייפול, ונועלת חזרה
    void releasePill(int compartmentID);

    // פונקציה שמחזירה באופן מיידי את המנוע לזווית הנעילה (LOCKED_ANGLE)
    void lockServo();
};

#endif // DISPENSER_H